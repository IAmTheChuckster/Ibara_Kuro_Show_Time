#!/usr/bin/env python3
"""Maintainer tool: print the FIXED_EDITS table used by index.html.

    python tools/gen_web_extras.py <ibarablk.zip or folder>

It unpacks the program, applies showtime_patch.apply_extras() and prints only the bytes that
changed, as (address, hex) runs, so the web page carries the same edits as the Python script.
Only changed bytes are listed (new code and text), never original program bytes.
"""
import importlib.util
import sys
from pathlib import Path

here = Path(__file__).resolve().parent.parent
spec = importlib.util.spec_from_file_location("sp", here / "showtime_patch.py")
sp = importlib.util.module_from_spec(spec); spec.loader.exec_module(sp)

inputs = sp.find_inputs(Path(sys.argv[1]))
prog = bytearray(sp.lz_decompress(sp.wordswap(inputs["ibarablk_u4"]), sp.PACK_START))
assert sp.sha1(prog) == sp.UNPACKED_PROGRAM_SHA1
orig = bytes(prog)
sp.apply_extras(orig, prog)
runs, i, n = [], 0, len(prog)
while i < n:
    if prog[i] == orig[i]:
        i += 1
        continue
    j = i
    while j < n and prog[j] != orig[j]:
        j += 1
    runs.append((sp.RAM_BASE + i, bytes(prog[i:j])))
    i = j
print("const FIXED_EDITS = [   // generated by tools/gen_web_extras.py: [address, new bytes]")
for a, b in runs:
    print(f'  [0x{a:08X}, "{b.hex()}"],')
print("];")
